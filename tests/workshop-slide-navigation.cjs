const assert=require("node:assert/strict");const fs=require("node:fs");
const deck=fs.readFileSync("lib/workshop/cairoDeck.ts","utf8");
const presenter=fs.readFileSync("app/present/[code]/page.tsx","utf8");
const slides=[...deck.matchAll(/\["([^"]*)","([^"]*)","([^"]*)"\]/g)];
assert.equal(slides.length,38,"The editable reference catalog remains 38 pages");
assert.ok(presenter.includes("docs.google.com/presentation/d/"),"Google Slides is the presentation source");
assert.ok(presenter.includes("<iframe"),"Google Slides embedded player should be used");
assert.ok(presenter.includes("embed?start=false&loop=false"),"Native Google Slides player is required");
assert.ok(!presenter.includes("setSourcePage"),"Local navigation must not disagree with Google Slides");
assert.ok(!presenter.includes("refpage_"),"No guessed slide IDs or hash navigation");
assert.ok(!presenter.includes("الصفحة {sourcePage}"),"No unsynchronized slide counter");
assert.ok(presenter.includes('selectedTool==="asloobi"'),"Activity activation must be explicit");
assert.ok(presenter.includes("setActivity(\"none\")"),"Activity overlay must be closable");
console.log("PASS: single Google Slides player, no unsynchronized local slide counter. Browser testing still required.");
